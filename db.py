"""Хранилище: кто есть кто, задачи, штрафы, оплаты и покупки.

Локально и в тестах — файл SQLite, на сервере — Postgres по строке postgres://…
"""

import sqlite3
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import date, datetime, timedelta
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

import rules
from rules import CHORES, FINE_PER_DAY, PEOPLE

SCHEMA = """
CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS people (
    person TEXT PRIMARY KEY,
    tg_id {bigint} NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS tasks (
    id {id},
    chore TEXT NOT NULL,
    assignee TEXT NOT NULL,
    due TEXT NOT NULL,
    done_on TEXT
);
CREATE TABLE IF NOT EXISTS fines (
    task_id {bigint} NOT NULL REFERENCES tasks (id),
    person TEXT NOT NULL,
    day TEXT NOT NULL,
    amount INTEGER NOT NULL,
    PRIMARY KEY (task_id, day)
);
CREATE TABLE IF NOT EXISTS payments (
    id {id},
    person TEXT NOT NULL,
    amount INTEGER NOT NULL,
    requested_at TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    decided_by TEXT,
    decided_at TEXT
);
CREATE TABLE IF NOT EXISTS purchases (
    id {id},
    item TEXT NOT NULL,
    person TEXT NOT NULL,
    bought_at TEXT NOT NULL
)
"""

SQLITE_TYPES = {"id": "INTEGER PRIMARY KEY", "bigint": "INTEGER"}
PG_TYPES = {"id": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "bigint": "BIGINT"}

# libpq падает на незнакомых параметрах в строке подключения (у Supabase там есть свои)
LIBPQ_PARAMS = {"sslmode", "sslrootcert", "channel_binding", "connect_timeout", "options", "application_name"}

TASKS_LOCK = 7262  # pg_advisory_lock: задачи заводит один запрос за раз

UNDO_WINDOW = timedelta(days=1)


@dataclass(frozen=True)
class Task:
    id: int
    chore: str
    assignee: str
    due: date
    done_on: date | None


@dataclass(frozen=True)
class Payment:
    id: int
    person: str
    amount: int
    status: str  # pending / confirmed / rejected


def _task(row) -> Task:
    done_on = date.fromisoformat(row["done_on"]) if row["done_on"] else None
    return Task(row["id"], row["chore"], row["assignee"], date.fromisoformat(row["due"]), done_on)


def _payment(row) -> Payment:
    return Payment(row["id"], row["person"], row["amount"], row["status"])


def _clean_pg_url(url: str) -> str:
    parts = urlsplit(url)
    query = urlencode([(k, v) for k, v in parse_qsl(parts.query) if k in LIBPQ_PARAMS])
    return urlunsplit(parts._replace(query=query))


class Store:
    def __init__(self, url: str):
        """`url` — путь к файлу SQLite (или ":memory:") либо строка postgres://…"""
        self.pg = url.startswith(("postgres://", "postgresql://"))
        if self.pg:
            import psycopg
            from psycopg.rows import dict_row

            self.db = psycopg.connect(_clean_pg_url(url), autocommit=True, row_factory=dict_row, prepare_threshold=None)
            for statement in SCHEMA.format(**PG_TYPES).split(";"):
                self.db.execute(statement)
        else:
            self.db = sqlite3.connect(url, check_same_thread=False)
            self.db.row_factory = sqlite3.Row
            self.db.executescript(SCHEMA.format(**SQLITE_TYPES))

    def close(self) -> None:
        self.db.close()

    @contextmanager
    def _tx(self):
        if self.pg:
            with self.db.transaction():
                yield
        else:
            with self.db:
                yield

    def _exec(self, sql: str, *args):
        return self.db.execute(sql.replace("?", "%s") if self.pg else sql, args)

    def _write(self, sql: str, *args):
        with self._tx():
            return self._exec(sql, *args)

    def _insert(self, sql: str, *args) -> int:
        """INSERT … RETURNING id, возвращает id новой строки."""
        with self._tx():
            return self._exec(sql + " RETURNING id", *args).fetchone()["id"]

    def _one(self, sql: str, *args):
        return self._exec(sql, *args).fetchone()

    # --- настройки ---

    def get_setting(self, key: str) -> str | None:
        row = self._one("SELECT value FROM settings WHERE key = ?", key)
        return row["value"] if row else None

    def set_setting(self, key: str, value: str) -> None:
        self._write(
            "INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value",
            key,
            value,
        )

    def get_chat_id(self) -> int | None:
        value = self.get_setting("chat_id")
        return int(value) if value else None

    def set_chat_id(self, chat_id: int) -> None:
        self.set_setting("chat_id", str(chat_id))

    def mark_once(self, key: str) -> bool:
        """True только при первом вызове с этим ключом — чтобы крон не напомнил дважды за день."""
        cur = self._write("INSERT INTO settings (key, value) VALUES (?, '1') ON CONFLICT (key) DO NOTHING", key)
        return cur.rowcount == 1

    # --- кто есть кто ---

    def person_by_tg(self, tg_id: int) -> str | None:
        row = self._one("SELECT person FROM people WHERE tg_id = ?", tg_id)
        return row["person"] if row else None

    def tg_of(self, person: str) -> int | None:
        row = self._one("SELECT tg_id FROM people WHERE person = ?", person)
        return row["tg_id"] if row else None

    def register(self, person: str, tg_id: int) -> str:
        """ok / already (это уже ты) / taken (место занято другим)."""
        owner = self.tg_of(person)
        if owner == tg_id:
            return "already"
        if owner is not None:
            return "taken"
        with self._tx():
            self._exec("DELETE FROM people WHERE tg_id = ?", tg_id)
            self._exec("INSERT INTO people (person, tg_id) VALUES (?, ?)", person, tg_id)
        return "ok"

    # --- задачи ---

    def task(self, task_id: int) -> Task | None:
        row = self._one("SELECT * FROM tasks WHERE id = ?", task_id)
        return _task(row) if row else None

    def tasks(self, chore: str) -> list[Task]:
        return [_task(r) for r in self._exec("SELECT * FROM tasks WHERE chore = ? ORDER BY id", chore)]

    def open_tasks(self) -> list[Task]:
        return [_task(r) for r in self._exec("SELECT * FROM tasks WHERE done_on IS NULL ORDER BY due, id")]

    def _add_task(self, chore: str, assignee: str, due: date) -> Task:
        task_id = self._insert(
            "INSERT INTO tasks (chore, assignee, due) VALUES (?, ?, ?)", chore, assignee, due.isoformat()
        )
        return Task(task_id, chore, assignee, due, None)

    def ensure_tasks(self, today: date) -> None:
        """Заводит следующие задачи: мусор — после выполнения, коврики — каждый месяц по календарю."""
        with self._tx():
            if self.pg:
                self._exec("SELECT pg_advisory_xact_lock(?)", TASKS_LOCK)
            for chore in CHORES.values():
                history = self.tasks(chore.key)
                last = history[-1] if history else self._add_task(chore.key, chore.order[0], chore.first_due)
                while last.done_on or (chore.monthly_day and last.due <= today):
                    last = self._add_task(
                        chore.key,
                        rules.next_in_order(chore.order, last.assignee),
                        rules.next_due(chore, last.due, last.done_on),
                    )

    def complete(self, task_id: int, today: date) -> Task | None:
        """Отмечает задачу и возвращает следующую по этой обязанности. None — если уже было отмечено."""
        task = self.task(task_id)
        if task is None or task.done_on:
            return None
        self._charge(task, today)
        cur = self._write("UPDATE tasks SET done_on = ? WHERE id = ? AND done_on IS NULL", today.isoformat(), task_id)
        if cur.rowcount == 0:
            return None
        self.ensure_tasks(today)
        return next(t for t in self.open_tasks() if t.chore == task.chore)

    # --- штрафы ---

    def _charge(self, task: Task, until: date) -> None:
        with self._tx():
            for day in rules.fined_dates(CHORES[task.chore], task.due, until):
                self._exec(
                    "INSERT INTO fines (task_id, person, day, amount) VALUES (?, ?, ?, ?) ON CONFLICT DO NOTHING",
                    task.id,
                    task.assignee,
                    day.isoformat(),
                    FINE_PER_DAY,
                )

    def sync_fines(self, today: date) -> None:
        """Начисляет штрафы за все дни просрочки по несделанным задачам. Повторный вызов ничего не удваивает."""
        for task in self.open_tasks():
            self._charge(task, today)

    def task_fine(self, task_id: int) -> int:
        return self._one("SELECT COALESCE(SUM(amount), 0) AS s FROM fines WHERE task_id = ?", task_id)["s"]

    def balance(self, person: str) -> int:
        fined = self._one("SELECT COALESCE(SUM(amount), 0) AS s FROM fines WHERE person = ?", person)["s"]
        paid = self._one(
            "SELECT COALESCE(SUM(amount), 0) AS s FROM payments WHERE person = ? AND status = 'confirmed'",
            person,
        )["s"]
        return fined - paid

    def balances(self) -> dict[str, int]:
        return {p: self.balance(p) for p in PEOPLE}

    # --- оплата штрафов ---

    def payment(self, payment_id: int) -> Payment | None:
        row = self._one("SELECT * FROM payments WHERE id = ?", payment_id)
        return _payment(row) if row else None

    def request_payment(self, person: str, now: datetime) -> Payment | None:
        """Заявка «я заплатил» на весь текущий долг. None — если долга нет."""
        row = self._one("SELECT * FROM payments WHERE person = ? AND status = 'pending'", person)
        if row:
            return _payment(row)
        amount = self.balance(person)
        if amount <= 0:
            return None
        payment_id = self._insert(
            "INSERT INTO payments (person, amount, requested_at) VALUES (?, ?, ?)", person, amount, now.isoformat()
        )
        return Payment(payment_id, person, amount, "pending")

    def _decide(self, payment_id: int, by: str, now: datetime, status: str) -> str:
        pay = self.payment(payment_id)
        if pay is None or pay.status != "pending":
            return "done"
        if pay.person == by:
            return "self"
        cur = self._write(
            "UPDATE payments SET status = ?, decided_by = ?, decided_at = ? WHERE id = ? AND status = 'pending'",
            status,
            by,
            now.isoformat(),
            payment_id,
        )
        return "ok" if cur.rowcount == 1 else "done"

    def confirm_payment(self, payment_id: int, by: str, now: datetime) -> str:
        """ok / self (себе подтверждать нельзя) / done (уже решено)."""
        return self._decide(payment_id, by, now, "confirmed")

    def reject_payment(self, payment_id: int, by: str, now: datetime) -> str:
        return self._decide(payment_id, by, now, "rejected")

    # --- продукты ---

    def buy(self, item: str, person: str, now: datetime) -> None:
        self._write("INSERT INTO purchases (item, person, bought_at) VALUES (?, ?, ?)", item, person, now.isoformat())

    def purchases(self, item: str) -> list[tuple[str, datetime]]:
        rows = self._exec("SELECT person, bought_at FROM purchases WHERE item = ? ORDER BY id", item)
        return [(r["person"], datetime.fromisoformat(r["bought_at"])) for r in rows]

    def last_purchase(self, item: str) -> tuple[str, datetime] | None:
        history = self.purchases(item)
        return history[-1] if history else None

    def next_buyer(self, item: str) -> str:
        return rules.next_buyer(self.purchases(item))

    def undo_last_purchase(self, person: str, now: datetime) -> str | None:
        """Отменяет свою последнюю покупку за последние сутки. Возвращает позицию или None."""
        row = self._one("SELECT id, item, bought_at FROM purchases WHERE person = ? ORDER BY id DESC LIMIT 1", person)
        if row is None or now - datetime.fromisoformat(row["bought_at"]) > UNDO_WINDOW:
            return None
        self._write("DELETE FROM purchases WHERE id = ?", row["id"])
        return row["item"]
